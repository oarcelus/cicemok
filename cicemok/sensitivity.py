def pce(samples, evals: list[np.ndarray], config: SensitivityConfiguration):
    polyno = generate_polynomials(config)

    X = polyno.evaluate_basis(samples)
    y = np.asarray(evals)
    uhat = np.linalg.lstsq(X, y, rcond=None)[0]

    return (
        polyno,
        uhat.T,
    )


def precompute_polynomial_bases(
    samples: np.ndarray, config: SensitivityConfiguration
) -> dict:
    """
    Precompute polynomial bases for all (p, q) combinations.

    Parameters
    ----------
    samples : np.ndarray
        The experimental design (nsamples, nfeatures).
    config : SensitivityConfiguration
        Configuration for generating polynomials. This configuration should
        have attributes 'minorder' and 'order' that define the range of p values.

    Returns
    -------
    dict
        A dictionary mapping each (p, q) tuple to a tuple (polynomial, poly_evals)
        where 'polynomial' is the polynomial object generated by generate_polynomials
        and 'poly_evals' is the result of evaluating its basis on the samples.
    """
    precomputed = {}
    q_values = np.linspace(0.5, 1, 5)

    logging.info("Starting precomputation of polynomial bases.")
    for q in q_values:
        for p in range(config.minorder, config.order + 1):
            logging.info(
                f"Precomputing polynomial basis for order p={p} and cross_truncation q={q:.3f}..."
            )
            # Create a local copy of the configuration to avoid side effects
            local_config = copy.deepcopy(config)
            local_config.order = p
            local_config.cross_truncation = q

            polynomial = generate_polynomials(local_config)
            poly_evals = polynomial.evaluate_basis(samples)

            # Determine the cardinality: number of polynomial basis elements
            if poly_evals.ndim > 1:
                cardinality = poly_evals.shape[1]
            else:
                cardinality = len(poly_evals)

            precomputed[(p, q)] = (polynomial, poly_evals)
            logging.info(
                f"Finished precomputation for (p={p}, q={q:.3f}). Cardinality: {cardinality}"
            )

    logging.info("Completed precomputation of polynomial bases.")

    return precomputed


