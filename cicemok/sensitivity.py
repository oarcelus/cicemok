def lars_loo_cv(X, y):
    """
    Perform Cross-Validation of LARS sparsity hyperparameters based on Leave-One-Out Error.

    Parameters
    ----------
    X : array-like, shape (n_samples, n_features)
        The measurement (design) matrix.
    y : array-like, shape (n_samples,)
        The target measurements.

    Returns
    -------
    eloo_min : float
        The minimum leave-one-out cross validation error obtained.
    uhat_min : array, shape (n_features,)
        The corresponding coefficient vector (sparse) achieving the minimal LOOCV error.
    """
    N = X.shape[0]

    eloo_min = np.inf
    uhat_min = np.zeros(X.shape[1], dtype=float)
    count_eloo = 0

    lars = Lars(fit_intercept=False, n_nonzero_coefs=N - 1)
    lars.fit(X, y)
    for uhat in lars.coef_path_.T[1:]:
        idnonzero = uhat != 0
        eloo = get_eloo(X[:, idnonzero], uhat[idnonzero], y)

        if eloo_min - eloo < -1e-8:
            count_eloo += 1
        else:
            if count_eloo > 0:
                count_eloo -= 1

            uhat_min = uhat
            eloo_min = eloo

        if count_eloo == 2:
            break

    idnonzero = uhat_min != 0
    uhat_min[idnonzero] = np.linalg.lstsq(X[:, idnonzero], y, rcond=None)[0]
    eloo_min = get_eloo(X[:, idnonzero], uhat_min[idnonzero], y)

    return eloo_min, uhat_min


