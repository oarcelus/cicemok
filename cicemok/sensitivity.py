def subspace_pursuit(K, X, y):
    """
    Subspace Pursuit for sparse recovery using iterative support selection and OLS fitting.

    Parameters
    ----------
    K : int
        Approximate upper bound on the signal sparsity such that K >= s,
        where s is the true sparsity level.
    X : ndarray, shape (n_samples, n_features)
        The measurement (or design) matrix.
    y : ndarray, shape (n_samples,)
        The vector of measurements.

    Returns
    -------
    uhat : ndarray, shape (n_features,)
        The estimated sparse coefficient vector. Coefficients corresponding
        to indices outside the recovered support remain zero.

    Notes
    -----
    This is an implementation inspired by Díaz (2018). It performs an initial support
    selection based on the largest absolute correlations between columns of X and y.
    Then, it iteratively refines the support by:
      1. Computing the residual,
      2. Selecting candidate indices based on correlations with the residual,
      3. Merging this candidate set with the current support,
      4. Solving an OLS problem on the union to estimate coefficients,
      5. Pruning back to K indices with the largest coefficient magnitudes.
    The algorithm stops when the residual norm fails to decrease or a maximum iteration
    count is reached.
    """

    uhat = np.zeros(X.shape[1], dtype=float)
    max_iter = X.shape[1]
    Kp = -K - 1

    # Initial estimation
    x = np.zeros(max_iter)
    corr = np.abs(X.T @ y)
    s0 = np.partition(corr, Kp)
    idk = np.nonzero(corr >= s0[Kp])[0]

    x[idk] = np.linalg.lstsq(X[:, idk], y, rcond=None)[0]
    ur0 = y - X @ x

    iter = 0
    while True:
        corr = np.abs(X.T @ ur0)
        s0 = np.partition(corr, Kp)
        idk2 = np.nonzero(corr >= s0[Kp])[0]
        idk2 = np.union1d(idk, idk2)

        x = np.zeros(max_iter)
        x[idk2] = np.linalg.lstsq(X[:, idk2], y, rcond=None)[0]

        # Updated support estimation
        idk0 = idk
        s0 = np.partition(np.abs(x), Kp)
        idk = np.nonzero(np.abs(x) >= s0[Kp])[0]

        # Update residual
        x = np.zeros(max_iter)
        x[idk] = np.linalg.lstsq(X[:, idk], y, rcond=None)[0]
        ur = y - X @ x

        # Break conditions
        iter += 1
        urhat = np.linalg.norm(ur)
        ur0hat = np.linalg.norm(ur0)
        if urhat >= ur0hat:
            idk = idk0
            ur0 = ur
            break

        if iter == max_iter:
            ur0 = ur
            break

    uhat[idk] = np.linalg.lstsq(X[:, idk], y, rcond=None)[0]

    return uhat


def get_eloo(X, x, y):
    """
    Compute the Leave-One-Out Cross-Validation (LOO-CV) error for an OLS fit.

    Parameters
    ----------
    X : ndarray, shape (n_samples, n_features)
        The observation (or design) matrix used for fitting the model.
    x : ndarray, shape (n_features,)
        The OLS coefficient estimates (i.e., the solution vector from the least-squares fit).
    y : ndarray, shape (n_samples,)
        The vector of model evaluations or target measurements.

    Returns
    -------
    eloo : float
        The normalized leave-one-out error, computed by adjusting the mean squared error
        of the leave-one-out residuals with a correction factor and normalizing by the
        sample variance of y.
    """
    n = y.shape[0]
    # Correction factors
    ATA = X.T @ X
    I_ATA = np.linalg.inv(ATA)
    h = (X @ I_ATA @ X.T).diagonal()
    hi = 1.0 - h

    tpn = float(n) * (1.0 + np.trace(I_ATA)) / (float(n) - float(X.shape[1]))

    # Leave One Out Error
    residual = (y - X @ x) / hi
    errloo = np.mean(residual**2)
    var = np.var(y, ddof=1)
    eloo = tpn * errloo / var

    return eloo


def generate_fn_basis(alpha, N: int, config: SensitivityConfiguration):
    fn_config = copy.deepcopy(config)
    fn_config.cross_truncation = 1.0
    d = fn_config.distribution.lower.shape[0]

    if alpha is None:
        combinations = [abs(count_number_coeffs(p, d, 1.0) - N) for p in range(1, 20)]
        order = combinations.index(min(combinations))
        fn_config.order = order
        alpha, polyno = generate_polynomials(fn_config)

        return alpha, polyno

    II = np.eye(d, d, dtype=int)

    # Calculate all possible forward neighboughrs
    I_NEW = II[np.newaxis, :, :]
    FWD = (I_NEW + alpha.T[:, np.newaxis, :]).reshape(d * alpha.shape[1], d)

    # Get all unique elements that are not already in alpha
    FWD = np.unique(FWD, axis=0)
    mask = ~np.any(np.all(FWD[:, np.newaxis] == alpha.T, axis=2), axis=1)
    FWD_UQ = FWD[mask]

    BWD = FWD_UQ[:, np.newaxis, :] - I_NEW

    comparison = BWD[:, :, np.newaxis, :] == alpha.T[np.newaxis, :, :]
    contained = np.any(np.all(comparison, axis=-1), axis=-1)
    idx = np.where(np.all(contained, axis=1))[0]

    return FWD_UQ[idx].T


def get_analytical_mean(fouriers):
    return np.array([fourier[0] for fourier in fouriers])


def get_analytical_variance(fouriers, alphas):
    return np.array([np.sum(fourier[1:] ** 2) for fourier in fouriers])


def get_analytical_sobol(fouriers, alphas, config: SensitivityConfiguration):
    dimension = len(config.distribution.marginals)
    ntrgt = len(fouriers)
    d_hat = get_analytical_variance(fouriers, alphas)

    sens_t_hat = None
    if config.sobol_total:
        sens_t_hat = np.empty((dimension, d_hat.shape[0]))
        for idx in range(dimension):
            index = [alpha[idx, :] > 0 for alpha in alphas]
            sens_t_hat[idx, :] = [
                np.sum((fouriers[i] * index[i]) ** 2) / d_hat[i] for i in range(ntrgt)
            ]

    sens_m2_hat = None
    if config.sobol_second:
        sens_m2_hat = np.empty((dimension, dimension, d_hat.shape[0]))
        for idx in range(dimension):
            for jdx in range(dimension):
                index = [
                    (idx != jdx)
                    & (alpha[idx, :] > 0)
                    & (alpha[jdx, :] > 0)
                    & (alpha.sum(0) == alpha[idx, :] + alpha[jdx, :])
                    for alpha in alphas
                ]
                sens_m2_hat[idx, jdx, :] = [
                    np.sum((fouriers[i] * index[i]) ** 2) / d_hat[i]
                    for i in range(ntrgt)
                ]

    sens_m_hat = np.empty((dimension, d_hat.shape[0]))
    for idx in range(dimension):
        index = [
            (alpha[idx, :] > 0) & (alpha.sum(0) == alpha[idx, :]) for alpha in alphas
        ]
        sens_m_hat[idx, :] = [
            np.sum((fouriers[i] * index[i]) ** 2) / d_hat[i] for i in range(ntrgt)
        ]

    return sens_t_hat, sens_m2_hat, sens_m_hat


